"""Run the spec's suggested questions through the agent and record traces to docs/example_runs.md.

Usage:  python scripts/run_examples.py [question numbers...]     e.g. python scripts/run_examples.py 1 3
"""

from __future__ import annotations

import asyncio
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

from client.agent import answer, load_settings  # noqa: E402

QUESTIONS = [
    "What World Bank reports exist on climate resilience in Kenya?",
    "Find documents about education financing in Sub-Saharan Africa published between 2019 and 2022.",
    "What document types does the World Bank publish most frequently?",
    "Find the most recent economic sector work on Indonesia.",
    "List all languages the World Bank publishes documents in.",
    "Find project documents related to water and sanitation in Brazil.",
]


async def run_one(number: int, settings) -> str:
    question = QUESTIONS[number - 1]
    trace: list[str] = []
    start = time.perf_counter()
    result = await answer(question, settings, on_event=trace.append)
    seconds = time.perf_counter() - start
    return (f"## Q{number}. {question}\n\n"
            f"Model: `{settings.provider}:{settings.model}` · {seconds:.0f}s\n\n"
            "**Tool trace**\n\n```text\n" + "\n".join(trace) + "\n```\n\n"
            f"**Answer**\n\n{result}\n")


async def main() -> None:
    load_dotenv(ROOT / ".env")
    settings = load_settings(os.environ)
    numbers = [int(n) for n in sys.argv[1:]] or list(range(1, len(QUESTIONS) + 1))
    sections = []
    for n in numbers:
        section = await run_one(n, settings)
        print(section, flush=True)
        sections.append(section)
    out = ROOT / "docs" / "example_runs.md"
    out.write_text("# Example runs\n\nGenerated by `python scripts/run_examples.py`.\n\n"
                   + "\n---\n\n".join(sections), encoding="utf-8")
    print(f"Saved to {out}")


if __name__ == "__main__":
    asyncio.run(main())
